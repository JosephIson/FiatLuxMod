package com.josephison.fiatlux.eden;

/** Where the story of the garden stands (Genesis 2-3). */
public enum EdenState {
    /** No garden has been planted. */
    NONE,
    /** "And they were both naked, the man and his wife, and were not ashamed" (Gen 2:25). */
    INNOCENCE,
    /** The serpent speaks with the woman (Gen 3:1-6). */
    TEMPTATION,
    /** "And the eyes of them both were opened" (Gen 3:7): they hide among the trees. */
    FALLEN,
    /** "Where art thou?" (Gen 3:9-19). */
    JUDGMENT,
    /** Driven out; cherubim and a flaming sword keep the way of the tree of life (Gen 3:24). */
    EXILED
}
